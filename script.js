document.addEventListener('DOMContentLoaded', () => {
    const jokeDisplay = document.getElementById('jokeDisplay');
    const generateButton = document.getElementById('generateButton');

    // ТВОЙ СПИСОК "ПЕРДЁЖНЫХ ФРАЗ" (можно добавить сотни!)
    const jokes = [
        "Газовый король на троне сидит, от каждого пука земля дрожит!",
        "О, это не ветер в трубах, это мой кишечник поет серенады!",
        "Когда желудок зовет, даже самые крепкие двери не устоят.",
        "Мой пердёж — как хорошее вино, с годами только крепче становится.",
        "Кто сказал 'гром'? Это просто моя еда решила заговорить.",
        "Я не порчу воздух, я добавляю ему характер!",
        "Это не запах, это ароматерапия для смелых.",
        "Молчаливый, но мощный — вот девиз моего кишечника.",
        "После таких звуков даже соседи начинают гадать: что это было?",
        "Мой внутренний мир хочет выйти наружу... с шумом.",
        "Пусть говорят, что пердёж — это невежливо. Я называю это 'звуковой атакой'!",
        "Когда душа просит праздника, а желудок — фанфар.",
        "Не беспокойтесь, это просто моё пищеварение аплодирует обеду.",
        "Иногда нужно просто отпустить... звук.",
        "Мой личный симфонический оркестр играет по расписанию."
    ];

    let lastJokeIndex = -1; // Чтобы не повторять одну и ту же шутку сразу

    // Функция для генерации случайной шутки
    function generateRandomJoke() {
        let newIndex;
        do {
            newIndex = Math.floor(Math.random() * jokes.length);
        } while (newIndex === lastJokeIndex && jokes.length > 1); // Избегаем повторов, если шуток больше одной
        
        lastJokeIndex = newIndex;
        jokeDisplay.textContent = jokes[newIndex];
        
        // Добавляем класс для анимации появления текста
        jokeDisplay.style.transform = 'scale(0.9)';
        setTimeout(() => {
            jokeDisplay.style.transform = 'scale(1)';
        }, 100);
    }

    // Привязываем функцию к кнопке
    generateButton.addEventListener('click', generateRandomJoke);

    // Генерируем первую шутку при загрузке страницы
    generateRandomJoke();
});